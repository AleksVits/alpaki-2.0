const assert = require('node:assert/strict');
const { baseUrl, launch } = require('./browser.cjs');
(async () => {
 const browser = await launch();
 const page = await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(baseUrl);
 const jump=async id=>{await page.locator('#'+id).evaluate(el=>el.scrollIntoView({behavior:'instant'}));await page.waitForTimeout(100)};
 await jump('about-stats');
 await page.locator('.header__burger').click();
 await page.waitForFunction(()=>document.querySelector('.site').inert);
 for(let i=0;i<20;i++){
  await page.keyboard.press('Tab');
  assert(await page.evaluate(()=>!!document.activeElement.closest('.header__menu-panel, .header__burger')),'Menu focus must stay in its controls');
 }
 await page.keyboard.press('Escape');
 await page.waitForFunction(()=>!document.querySelector('.site').inert&&!document.documentElement.classList.contains('is-nav-lock'));
 assert(await page.locator('.header__burger').evaluate(el=>el===document.activeElement));
 await page.locator('.header__burger').click();
 await page.locator('.header__menu-panel a[href="#contacts"]').click();
 await page.waitForFunction(()=>location.hash==='#contacts');
 await page.goBack();
 await page.waitForFunction(()=>document.querySelector('.site').scrollTop<2);
 await page.evaluate(()=>location.hash='#apartments');
 await page.waitForFunction(()=>Math.abs(document.querySelector('#apartments').getBoundingClientRect().top)<2);
 await page.locator('.apt__copy .btn').click();
 await page.locator('.apt-house > .btn').click();
 assert.equal(await page.locator('.apt-floor').count(),1,'House selection must lead to floors');
 await page.locator('.apt-floor__list button').last().click();
 await page.locator('.apt-floor__copy .btn').click();
 assert.match(await page.locator('.apt-3d__meta').innerText(),/05/);
 // The price request carries the chosen building, floor and type into the form.
 await page.locator('.apt-3d__copy .btn').click();
 await page.waitForFunction(()=>location.hash==='#contacts');
 assert.match(await page.locator('[name="message"]').inputValue(),/Vista.*05.*студія/);
 // A message the visitor wrote is never replaced; an emptied field takes the next request.
 await page.locator('[name="message"]').fill('Свій текст');
 await jump('invest-formats');
 await page.locator('.invest__actions .btn').first().click();
 await page.waitForFunction(()=>location.hash==='#contacts');
 assert.equal(await page.locator('[name="message"]').inputValue(),'Свій текст');
 await page.locator('[name="message"]').fill('');
 await jump('invest-manage');
 await page.locator('.manage__foot .btn').click();
 await page.waitForFunction(()=>location.hash==='#contacts');
 assert.match(await page.locator('[name="message"]').inputValue(),/умови управління/);
 // The pager walks the same path as the buttons: type → building → floor → 3D.
 await jump('apartments');
 const nextApt=()=>page.locator('#apartments .pager__btn').last().evaluate(el=>el.click());
 await nextApt();
 for(const screen of ['.apt-types','.apt-house','.apt-floor','.apt-3d']){
  assert.equal(await page.locator('#apartments '+screen).count(),1,`Pager must show ${screen}`);
  await nextApt();
 }
 assert.equal(await page.locator('h1').count(),1,'The page needs exactly one h1');
 await jump('architecture');
 await page.locator('.thumbs__item').first().click();
 assert(await page.locator('#architecture').evaluate(el=>el.classList.contains('is-viewing')));
 await page.locator('.architecture__viewer-close').click();
 assert(await page.locator('#architecture').evaluate(el=>!el.classList.contains('is-viewing')));
 await jump('construction');
 await page.locator('.build-line li button').nth(1).click();
 assert.equal(await page.locator('.build-detail__empty').count(),1);
 await page.locator('.build-line li button').first().click();
 assert.equal(await page.locator('.build-detail__thumbs button').count(),3);
 for(const [width,height] of [[320,480],[844,320],[1024,768],[1366,768],[1920,1080],[3840,2160]]){
  await page.setViewportSize({width,height});
  await jump('contacts');
  await page.locator('.form__check button').click();
  assert(await page.locator('dialog').evaluate(el=>el.matches(':modal')));
  await page.keyboard.press('Tab');
  assert(await page.evaluate(()=>document.activeElement===document.body||document.activeElement.closest('dialog')!==null));
  const valid=await page.locator('.modal__card').evaluate(el=>{
   const r=el.getBoundingClientRect();return r.x>=0&&r.right<=innerWidth&&r.y>=0&&r.bottom<=innerHeight+1&&el.scrollWidth<=el.clientWidth+1;
  });assert(valid,`Dialog must fit ${width}x${height}`);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('dialog').count(),0);
  assert(await page.locator('.form__check button').evaluate(el=>el===document.activeElement),'Dialog must restore focus');
  await jump('apartments');
  const gap=await page.locator('#apartments').evaluate(el=>el.querySelector('.scroll-hint').getBoundingClientRect().top-el.querySelector('.apt__pager').getBoundingClientRect().bottom);
  assert(gap>=31,`Pager/next arrow gap ${gap} at ${width}`);
 }
 await page.setViewportSize({width:1920,height:1080});
 await jump('infrastructure');
 await page.locator('.infra-card').nth(1).click();
 await page.waitForTimeout(200);
 assert.equal(await page.locator('.header__nav a[aria-current="location"]').getAttribute('data-nav-id'),'infra');
 await jump('contacts');
 await page.locator('[name="name"]').fill('Test');
 await page.locator('[name="email"]').fill('test@example.com');
 await page.locator('[name="phone"]').fill('+380000000000');
 await page.locator('.form__check input').check();
 await page.locator('.form button[type="submit"]').click();
 assert.match(await page.locator('.form [role="status"]').innerText(),/поштовій/);
 assert.equal(await page.locator('[name="name"]').inputValue(),'Test');
 const animated=await browser.newPage({viewport:{width:320,height:480},hasTouch:true});
 await animated.goto(baseUrl);
 await animated.waitForFunction(()=>getComputedStyle(document.querySelector('.intro')).opacity==='1');
 await animated.locator('#about-stats').evaluate(el=>el.scrollIntoView({behavior:'instant'}));
 await animated.locator('.header__burger').click();
 await animated.locator('.header__langs--menu button').last().click();
 assert.equal(await animated.locator('html').getAttribute('lang'),'en');
 assert.equal(animated.url(),baseUrl+'en/','English must have its own address');
 assert.match(await animated.title(),/private space/);
 await animated.keyboard.press('Escape');
 await animated.waitForFunction(()=>!document.documentElement.classList.contains('is-nav-lock'));
 await animated.goto(baseUrl);
 await animated.waitForFunction(()=>document.documentElement.lang==='en');
 assert.equal(animated.url(),baseUrl+'en/','Saved language must be restored at the site root');
 await animated.locator('#about-stats').evaluate(el=>el.scrollIntoView({behavior:'instant'}));
 await animated.locator('.header__burger').click();
 await animated.locator('.header__langs--menu button').first().click();
 await animated.waitForFunction(()=>document.documentElement.lang==='uk');
 assert.equal(animated.url(),baseUrl);
 await animated.keyboard.press('Escape');
 await animated.waitForFunction(()=>!document.documentElement.classList.contains('is-nav-lock'));
 await animated.close();
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('PASS: navigation/history, menu focus, apartment flow, gallery, construction, responsive dialog, pager spacing, form draft and request context, language address.');
})().catch(e=>{console.error(e);process.exit(1)});
